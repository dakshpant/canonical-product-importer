import { z } from "zod";

import { MAPPED_FIELDS, allowedValues } from "../constants/taxonomy.js";

// ---------------------------------------------------------------------------
// Field lists: the only fields the AI is allowed to propose.
// ---------------------------------------------------------------------------

export const TEXT_FIELDS = [
  "name",
  "product_kind",
  "category",
  "industry",
  "sub_category",
  "tagline",
  "short_description",
  "overview",
  "image_alt",
];

export const URL_FIELDS = ["website", "image_url", "image_source_page"];

export const SCALAR_FIELDS = [...TEXT_FIELDS, ...URL_FIELDS];

export const LIST_FIELDS = [
  "tags",
  "skills",
  "features",
  "deployments",
  "platforms",
  "target_customers",
];

// Canonical order, matching the Product model.
export const PRODUCT_EXTRACTION_FIELDS = [
  "name",
  "product_kind",
  "category",
  "industry",
  "sub_category",
  "tagline",
  "short_description",
  "overview",
  "website",
  "image_url",
  "image_alt",
  "image_type",
  "image_source_page",
  ...LIST_FIELDS,
];

export const AI_PRODUCT_EXTRACTION_FIELDS = PRODUCT_EXTRACTION_FIELDS.filter(
  (field) => field !== "image_type",
);

// Generated by the application or entered by the admin. The AI must never
// return them, and neither may it return any lifecycle/approval field.
export const FORBIDDEN_FIELDS = [
  "sku_id",
  "slug",
  "unit_of_measure",
  "min_quantity",
  "max_quantity",
  "status",
  "id",
];

// Where a piece of evidence was found in the extraction input.
// Matches the sections of buildProductExtractionInput().
export const SOURCE_TYPES = ["json_ld", "metadata", "page_text"];

const TEXT_LIMITS = {
  name: 200,
  product_kind: 100,
  category: 150,
  industry: 150,
  sub_category: 150,
  tagline: 300,
  short_description: 1000,
  overview: 5000,
  image_alt: 300,
};

const MAX_LIST_ITEMS = 50;
const MAX_LIST_ITEM_LENGTH = 200;
const MAX_SOURCES = 150;
const MAX_EVIDENCE_LENGTH = 1000;

// ---------------------------------------------------------------------------
// Normalisers: tidy harmless LLM quirks before validating.
// ---------------------------------------------------------------------------

// "  " or "" -> null, strings trimmed. Anything else is left for Zod to reject.
function blankToNull(value) {
  if (typeof value !== "string") return value;
  const trimmed = value.trim();
  return trimmed === "" ? null : trimmed;
}

// Trim items, drop empty ones, and remove case-insensitive duplicates.
function cleanList(value) {
  if (!Array.isArray(value)) return value;

  const seen = new Set();
  const cleaned = [];

  for (const item of value) {
    if (typeof item !== "string") {
      cleaned.push(item); // let Zod report the wrong type
      continue;
    }
    const trimmed = item.replace(/\s+/g, " ").trim();
    const key = trimmed.toLowerCase();
    if (!trimmed || seen.has(key)) continue;
    seen.add(key);
    cleaned.push(trimmed);
  }

  return cleaned;
}

const nullableText = (maxLength) =>
  z.preprocess(blankToNull, z.string().max(maxLength).nullable());

// http/https only: rejects javascript:, data:, ftp: and relative URLs.
const nullableHttpUrl = z.preprocess(
  blankToNull,
  z
    .url({
      protocol: /^https?$/,
      error: "Must be an absolute http(s) URL.",
    })
    .nullable(),
);

const stringList = z.preprocess(
  cleanList,
  z.array(z.string().max(MAX_LIST_ITEM_LENGTH)).max(MAX_LIST_ITEMS),
);

// ---------------------------------------------------------------------------
// Schemas
// ---------------------------------------------------------------------------

/**
 * One piece of evidence, as returned by the LLM.
 * source_url is NOT asked from the LLM: the application sets it to the page
 * URL it actually fetched, so it can never be fabricated. The stored shape
 * (with source_url) matches the ProductSource model.
 */
export const sourceSchema = z
  .object({
    field_name: z.enum(AI_PRODUCT_EXTRACTION_FIELDS),
    extracted_value: z.union([
      z.string().trim().min(1).max(MAX_EVIDENCE_LENGTH),
      z.array(z.string().trim().min(1).max(MAX_LIST_ITEM_LENGTH)).min(1),
    ]),
    // The model's quote is only used to find the line on the page (the
    // evidence stored and shown is the page's own line), so an over-long
    // quote is cut rather than rejecting the whole answer.
    evidence_text: z
      .string()
      .trim()
      .min(1)
      .transform((text) => text.slice(0, MAX_EVIDENCE_LENGTH)),
    source_type: z.enum(SOURCE_TYPES),
  })
  .strict();

const fieldShape = {};
for (const field of TEXT_FIELDS)
  fieldShape[field] = nullableText(TEXT_LIMITS[field]);
for (const field of URL_FIELDS) fieldShape[field] = nullableHttpUrl;
for (const field of LIST_FIELDS) fieldShape[field] = stringList;

/**
 * Final structural boundary for LLM output.
 * - Every key is required (null / [] when unknown), none may be added.
 * - Forbidden fields (sku_id, slug, quantities, status, ...) are rejected.
 */
export const productExtractionSchema = z
  .object({
    ...fieldShape,
    sources: z.array(sourceSchema).max(MAX_SOURCES),
  })
  .strict();

export function validateProductExtraction(data) {
  // .strict() would reject forbidden keys as generic "unrecognized" keys;
  // check them first so the reason is explicit.
  if (data && typeof data === "object" && !Array.isArray(data)) {
    const forbidden = FORBIDDEN_FIELDS.filter((field) =>
      Object.hasOwn(data, field),
    );
    if (forbidden.length > 0) {
      return {
        success: false,
        error: new z.ZodError(
          forbidden.map((field) => ({
            code: "custom",
            path: [field],
            message: `${field} must never be returned by the AI.`,
            input: data[field],
          })),
        ),
      };
    }
  }

  return productExtractionSchema.safeParse(data);
}

// Short, readable list of problems, e.g. for a retry message or a log line.
export function formatValidationIssues(error, limit = 10) {
  return error.issues
    .slice(0, limit)
    .map((issue) => `${issue.path.join(".") || "(root)"}: ${issue.message}`)
    .join("; ");
}

// ---------------------------------------------------------------------------
// JSON Schema for Groq structured outputs (strict mode).
// Strict mode requires every property in `required` and
// additionalProperties: false; nullable fields use a type array.
// Length limits stay in Zod, which is the real trust boundary.
// ---------------------------------------------------------------------------

const nullableStringJson = { type: ["string", "null"] };
const stringListJson = { type: "array", items: { type: "string" } };

const sourceJsonSchema = {
  type: "object",
  properties: {
    field_name: { type: "string", enum: AI_PRODUCT_EXTRACTION_FIELDS },
    extracted_value: {
      anyOf: [{ type: "string" }, stringListJson],
    },
    evidence_text: { type: "string" },
    source_type: { type: "string", enum: SOURCE_TYPES },
  },
  required: ["field_name", "extracted_value", "evidence_text", "source_type"],
  additionalProperties: false,
};

const productProperties = {};
for (const field of SCALAR_FIELDS)
  productProperties[field] = nullableStringJson;
for (const field of LIST_FIELDS) productProperties[field] = stringListJson;

// Classification fields: the model must pick from the fixed list.
// Zod above still accepts any string, so one off-list value is discarded by
// the verifier (with a reason) instead of failing the whole record.
for (const field of MAPPED_FIELDS) {
  const values = allowedValues(field);
  productProperties[field] = LIST_FIELDS.includes(field)
    ? { type: "array", items: { type: "string", enum: values } }
    : { type: ["string", "null"], enum: [...values, null] };
}

export const productExtractionJsonSchema = {
  type: "object",
  properties: {
    ...Object.fromEntries(
      AI_PRODUCT_EXTRACTION_FIELDS.map((field) => [
        field,
        productProperties[field],
      ]),
    ),
    sources: { type: "array", items: sourceJsonSchema },
  },
  required: [...AI_PRODUCT_EXTRACTION_FIELDS, "sources"],
  additionalProperties: false,
};
