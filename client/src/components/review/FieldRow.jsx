import { useState } from 'react'

import { ORIGIN, ORIGIN_LABEL, isEmpty, toList } from '../../utils/fields.js'
import { Badge } from '../common/StatusBadge.jsx'
import { EvidenceQuote, FieldNote } from './Evidence.jsx'

export const inputClass =
  'block w-full rounded-md border-0 bg-white px-3 py-2 text-sm text-stone-800 ring-1 ring-inset ring-stone-300 placeholder:text-stone-400 focus:ring-2 focus:ring-stone-800 focus:outline-none disabled:bg-stone-50 disabled:text-stone-500'

const norm = (v) => String(v ?? '').replace(/\s+/g, ' ').trim().toLowerCase()

/** Sources whose value supports the currently saved value. */
function supportingSources(field, savedValue, sources) {
  if (field.list) {
    const items = new Set(toList(savedValue).map(norm))
    return sources.filter((s) =>
      (Array.isArray(s.extracted_value) ? s.extracted_value : [s.extracted_value]).some((v) => items.has(norm(v))),
    )
  }
  return sources.filter((s) => norm(s.extracted_value) === norm(savedValue))
}

const ORIGIN_TONE = { [ORIGIN.SCRAPED]: 'neutral', [ORIGIN.GENERATED]: 'neutral', [ORIGIN.ADMIN]: 'info' }

/**
 * One canonical field: label, input, and the evidence behind its value.
 * savedValue is what is stored; value is the (possibly edited) form value.
 */
export default function FieldRow({ field, value, savedValue, sources, onChange, missingRequired }) {
  const [showAll, setShowAll] = useState(false)
  const edited = value !== undefined && isDirty(field, value, savedValue)
  const supporting = supportingSources(field, savedValue, sources)
  const shown = showAll ? supporting : supporting.slice(0, 2)
  const id = `field-${field.name}`

  return (
    <div id={id} className="grid scroll-mt-24 gap-x-6 gap-y-2 py-4 sm:grid-cols-[11rem_minmax(0,1fr)]">
      <div className="pt-2">
        <label htmlFor={`${id}-input`} className="text-sm font-medium text-stone-800">
          {field.label}
          {field.required && <span className="ml-0.5 text-rose-500" title="Required">*</span>}
        </label>
        <div className="mt-1 flex flex-wrap gap-1">
          <Badge tone={ORIGIN_TONE[field.origin]}>{ORIGIN_LABEL[field.origin]}</Badge>
          {edited && <Badge tone="warning">Edited</Badge>}
        </div>
      </div>

      <div className="min-w-0 space-y-2">
        <FieldInput id={`${id}-input`} field={field} value={value} onChange={onChange} invalid={missingRequired} />
        <FieldEvidence field={field} savedValue={savedValue} supporting={shown} total={supporting.length} sources={sources} missingRequired={missingRequired} />
        {supporting.length > 2 && (
          <button type="button" onClick={() => setShowAll((s) => !s)} className="text-xs text-stone-500 hover:text-stone-800">
            {showAll ? 'Show less' : `Show ${supporting.length - 2} more sources`}
          </button>
        )}
      </div>
    </div>
  )
}

function isDirty(field, value, savedValue) {
  if (field.list) return value.trim() !== toList(savedValue).join('\n').trim()
  return String(value).trim() !== String(savedValue ?? '').trim()
}

function FieldInput({ id, field, value, onChange, invalid }) {
  const ring = invalid ? 'ring-amber-400! bg-amber-50/30' : ''

  if (field.origin === ORIGIN.GENERATED) {
    return (
      <div className="rounded-md bg-stone-50 px-3 py-2 font-mono text-sm text-stone-600 ring-1 ring-inset ring-stone-200">
        {value || <span className="font-sans text-stone-400">Assigned when the product is created</span>}
      </div>
    )
  }

  if (field.list) {
    return (
      <textarea
        id={id}
        rows={Math.min(8, Math.max(2, value.split('\n').length))}
        value={value}
        onChange={(e) => onChange(field.name, e.target.value)}
        placeholder="One item per line"
        className={`${inputClass} ${ring} resize-y`}
      />
    )
  }

  if (field.multiline) {
    return (
      <textarea
        id={id}
        rows={field.rows ?? 3}
        value={value}
        onChange={(e) => onChange(field.name, e.target.value)}
        className={`${inputClass} ${ring} resize-y`}
      />
    )
  }

  return (
    <input
      id={id}
      type={field.type === 'number' ? 'number' : 'text'}
      inputMode={field.type === 'number' ? 'decimal' : undefined}
      min={field.type === 'number' ? 0 : undefined}
      value={value}
      onChange={(e) => onChange(field.name, e.target.value)}
      placeholder={field.origin === ORIGIN.ADMIN ? 'Enter manually' : field.type === 'url' ? 'https://' : undefined}
      className={`${inputClass} ${ring} ${field.type === 'url' ? 'font-mono text-[13px]' : ''}`}
    />
  )
}

function FieldEvidence({ field, savedValue, supporting, total, sources, missingRequired }) {
  if (field.origin === ORIGIN.GENERATED) {
    return <FieldNote>Generated by the app and unique. Never scraped.</FieldNote>
  }

  if (field.origin === ORIGIN.ADMIN) {
    return <FieldNote>Admin entry only. The app never fills this in.</FieldNote>
  }

  if (isEmpty(savedValue)) {
    return (
      <FieldNote tone="warning">
        {missingRequired ? 'Required. ' : ''}Not found on the page. Fill it in or leave it empty.
      </FieldNote>
    )
  }

  if (total === 0) {
    return (
      <FieldNote tone="info">
        {sources.length > 0
          ? 'Differs from the page evidence (edited or chosen by you).'
          : 'No page evidence on record for this value (entered by hand or seeded).'}
      </FieldNote>
    )
  }

  return (
    <div className="space-y-1.5">
      {supporting.map((source) => (
        <EvidenceQuote key={source.id ?? `${source.field_name}-${source.evidence_text}`} source={source} />
      ))}
    </div>
  )
}
